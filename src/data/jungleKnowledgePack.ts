let hydratedDdragon: DdragonHydratedCatalog | null = null;

export function hydrateDdragonCatalog(catalog: DdragonHydratedCatalog): void {
  hydratedDdragon = catalog;
}

export function getHydratedDdragonCatalog(): DdragonHydratedCatalog | null {
  return hydratedDdragon;
}

export function resolveItemMetadata(itemId: number): ItemMetadata | undefined {
  const curated = ITEM_CATALOG[itemId];
  if (curated) return curated;
  const dd = hydratedDdragon?.itemsById[itemId];
  if (!dd) return undefined;
  return {
    id: dd.id,
    name: dd.name,
    cost: dd.cost,
    tags: [],
    shortReason: 'Live Data Dragon item',
  };
}

export function findJungleChampionById(championId: number): JungleChampionProfile | undefined {
  return JUNGLE_CHAMPIONS.find((c) => c.championId === championId);
}

export function findJungleChampionByName(name: string): JungleChampionProfile | undefined {
  const normalized = name.toLowerCase().replace(/[^a-z0-9]/g, '');
  return JUNGLE_CHAMPIONS.find(
    (c) =>
      c.name.toLowerCase().replace(/[^a-z0-9]/g, '') === normalized ||
      c.key.toLowerCase().replace(/[^a-z0-9]/g, '') === normalized
  );
}

export function getChampionMeta(championId: number): ChampionMetaEntry {
  const curated = CHAMPION_META_TABLE[championId];
  if (curated) return curated;

  const dd = hydratedDdragon?.championsById[championId];
  if (dd) {
    const isMage = dd.tags.includes('Mage') || dd.tags.includes('Support');
    const isTank = dd.tags.includes('Tank');
    return {
      championId,
      key: dd.key,
      name: dd.name,
      damageProfile: isTank ? 'tank' : isMage ? 'ap' : 'ad',
      championClass: isTank ? 'tank' : isMage ? 'mage' : 'bruiser',
      engageScore: isTank ? 7 : 5,
      hardCcScore: isTank ? 7 : 4,
      frontlineScore: isTank ? 8 : 3,
      powerSpike: 'mid',
    };
  }

  return {
    championId,
    key: `Champ${championId}`,
    name: `Champion #${championId}`,
    damageProfile: 'ad',
    championClass: 'bruiser',
    engageScore: 5,
    hardCcScore: 4,
    frontlineScore: 4,
    powerSpike: 'mid',
  };
}

